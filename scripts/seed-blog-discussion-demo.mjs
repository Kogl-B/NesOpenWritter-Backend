const reactions = ['like', 'like', 'like', 'heart', 'heart', 'fire', 'clap', 'book', 'fire'];
const authorId = (index) => 'ow-demo-discussion-author-' + index;
const readerId = (index) => 'ow-demo-discussion-reader-' + index;
const postId = (key) => 'ow-demo-discussion-' + key;

try {
  await db.$transaction(async (tx) => {
    await tx.user.createMany({
      data: [
        ...authors.map((name, index) => ({ id: authorId(index), name: name + ' · демо' })),
        ...reactions.map((_, index) => ({ id: readerId(index), name: 'Демо-читатель ' + (index + 1) })),
      ].map((user) => ({ ...user, email: user.id + '@example.test' })),
      skipDuplicates: true,
    });
    const now = Date.now();
    await tx.blogPost.createMany({
      data: posts.map((post, index) => ({
        id: postId(post.key), authorId: authorId(post.author), title: post.title,
        body: post.parts.map((part) => '<p>' + part + '</p>').join(''),
        topic: post.topic, tags: ['демо', ...post.tags], published: true,
        createdAt: new Date(now - (index + 1) * 3600000),
        publishedAt: new Date(now - (index + 1) * 3600000),
      })),
      skipDuplicates: true,
    });
    await tx.blogLike.createMany({
      data: posts.flatMap((post, index) => reactions.slice(0, reactions.length - index).map((emoji, reader) => ({
        userId: readerId(reader), postId: postId(post.key), emoji,
      }))),
      skipDuplicates: true,
    });
    const checklist = Buffer.from('Проверка главы\n1. У каждой сцены есть вопрос.\n2. Следующая сцена продолжает действие или меняет задачу.\n3. Последний абзац прочитан вместе с переходом.\n');
    const commentId = 'ow-demo-discussion-checklist';
    const comments = [
      { id: commentId, postId: postId('notes'), userId: authorId(1), authorName: authors[1] + ' · демо', body: 'Обещанная памятка по проверке главы.' },
      { id: 'ow-demo-discussion-ferry-reply', postId: postId('ferry'), userId: readerId(2), authorName: 'Демо-читатель 3', body: 'Я бы остановил сцену на банке под скамьёй. После этого решения ясно, что Лида никуда не опаздывает.' },
    ];
    await tx.blogComment.createMany({ data: comments, skipDuplicates: true });
    await tx.blogCommentFile.createMany({
      data: [{ id: commentId, commentId, name: 'Памятка по проверке главы.txt', size: checklist.length, data: checklist }],
      skipDuplicates: true,
    });
  });
  console.log('Доступно демозаписей ' + posts.length + ', длинных ' + posts.filter((post) => post.parts.length > 4).length);
} finally {
  await db.$disconnect();
}
